"""Optional maintainer tool: python scripts/prepare-fonts.py.

Requires fonttools[woff] (Brotli or brotlicffi). Generated web fonts and CSS
are committed, so normal pnpm builds never need Python or network access.
Sources are read-only. All font output stays under assets/.
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'webfonts'
OUT.mkdir(exist_ok=True)
rules = ['/* Generated by scripts/prepare-fonts.py. Do not edit manually. */']


def rule(family, filename, weight=400, style='normal', unicode_range=None):
    css = (f'@font-face {{ font-family: "{family}"; font-style: {style}; '
           f'font-weight: {weight}; font-display: swap; '
           f'src: url("./{filename}") format("woff2");')
    if unicode_range:
        css += f' unicode-range: {unicode_range};'
    rules.append(css + ' }')


# Range subsets cover every encoded glyph, including uncommon characters.
# Browsers only fetch the ranges used on the page, not the entire 25 MB TTF.
source = ROOT / 'assets/LXGW/LXGWWenKai-Regular.ttf'
font = TTFont(source, recalcTimestamp=False)
codepoints = sorted(font.getBestCmap())
blocks = sorted({point // 256 for point in codepoints})
font.close()
for block in blocks:
    low, high = block * 256, block * 256 + 255
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    options.name_IDs = ['*']
    options.name_languages = ['*']
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=[point for point in codepoints if low <= point <= high])
    subsetter.subset(font)
    font.flavor = 'woff2'
    filename = f'lxgw-wenkai-{low:04x}.woff2'
    font.save(OUT / filename)
    font.close()
    rule('LXGW WenKai', filename, unicode_range=f'U+{low:X}-{high:X}')
print(f'LXGW WenKai: {len(blocks)} Unicode ranges', flush=True)

for style, weight, css_style in [('Regular', 400, 'normal'), ('Bold', 700, 'normal'), ('Italic', 400, 'italic')]:
    source = ROOT / f'assets/nerd-fonts/0xProto/0xProtoNerdFontMono-{style}.ttf'
    font = TTFont(source, recalcTimestamp=False)
    font.flavor = 'woff2'
    filename = f'0xproto-mono-{style.lower()}.woff2'
    font.save(OUT / filename)
    font.close()
    rule('0xProto Nerd Font Mono', filename, weight, css_style)

(OUT / 'fonts.css').write_text('\n'.join(rules) + '\n', encoding='utf-8')
print(f'Web fonts saved in {OUT}', flush=True)
